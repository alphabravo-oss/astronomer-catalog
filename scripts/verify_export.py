#!/usr/bin/env python3
"""Check the retained hashed export without machine-specific uv command headers."""

from __future__ import annotations

import argparse
import pathlib


def export_body(value: str) -> str:
    lines = value.splitlines(keepends=True)
    if lines and lines[0].strip() == "# This file was autogenerated by uv via the following command:":
        if len(lines) < 3 or not lines[1].startswith("#    uv "):
            raise ValueError("unexpected uv export header")
        lines = lines[2:]
    return "".join(lines).lstrip("\n")


def verify_export(reference: str, candidate: str) -> None:
    if export_body(reference) != export_body(candidate):
        raise ValueError("hashed export differs from the retained full locked graph")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--reference", type=pathlib.Path, required=True)
    parser.add_argument("--candidate", type=pathlib.Path, required=True)
    args = parser.parse_args()
    verify_export(args.reference.read_text(), args.candidate.read_text())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
