class ToolchainContractTest(unittest.TestCase):
    def test_export_only_ignores_machine_specific_command_header(self) -> None:
        body = "pyyaml==6.0.3 \\\n    --hash=sha256:" + "a" * 64 + "\n"
        verify_export(body, "# This file was autogenerated by uv via the following command:\n"
                      "#    uv export --output-file /owned/output\n\n" + body)
        for changed in (body.replace("6.0.3", "6.0.2"), body + "extra==1\n",
                        body.replace("a" * 64, "b" * 64), "# unknown\n" + body):
            with self.subTest(changed=changed), self.assertRaises(ValueError):
                verify_export(body, changed)

    def test_normalization_preserves_exact_versions(self) -> None:
        self.assertEqual(package_name("Types_PyYAML"), "types-pyyaml")
        for name in ("../package", "a b", "é", "a/thing", "-name"):
            with self.subTest(name=name), self.assertRaises(ValueError):
                package_name(name)
        verify_versions({"pyyaml": "6.0.3"}, {"pyyaml": "6.0.3"})
        for actual in ({}, {"pyyaml": "6.0.2"}, {"pyyaml": "6.0.3", "other": "1"}):
            with self.subTest(actual=actual), self.assertRaises(ValueError):
                verify_versions({"pyyaml": "6.0.3"}, actual)

    def test_locked_source_exception_has_one_package(self) -> None:
        import tomllib

        lock = tomllib.loads((ROOT / "uv.lock").read_text())
        names = locked_names(lock)
        self.assertEqual(len(names), 62)
        backend, complete = commands("selected-uv", "selected-python", names)
        self.assertIn("--no-build", backend)
        self.assertIn("--only-group", backend)
        self.assertIn("build-backend", backend)
        self.assertEqual(complete.count("--no-binary-package"), 1)
        self.assertEqual(complete[complete.index("--no-binary-package") + 1], "pyyaml")
        self.assertEqual(complete[complete.index("--no-build-isolation-package") + 1], "pyyaml")
        forbidden_builds = {complete[i + 1] for i, value in enumerate(complete)
                            if value == "--no-build-package"}
        self.assertEqual(forbidden_builds, set(names) - {"pyyaml"})
        for command in (backend, complete):
            self.assertIn("--locked", command)
            self.assertNotIn("--frozen", command)
            self.assertIn("--no-config", command)

    def test_new_source_or_unhashed_graph_rejects(self) -> None:
        import tomllib

        original = tomllib.loads((ROOT / "uv.lock").read_text())
        for kind in ("python", "index", "hash", "pyyaml"):
            lock = copy.deepcopy(original)
            row = next(row for row in lock["package"] if row["name"] == "pyyaml")
            if kind == "python":
                lock["requires-python"] = ">=3.15"
            elif kind == "index":
                row["source"]["registry"] = "https://other.example/simple"
            elif kind == "hash":
                row["sdist"]["hash"] = "sha256:bad"
            else:
                row["version"] = "6.0.4"
            with self.subTest(kind=kind), self.assertRaises(ValueError):
                locked_names(lock)

    def test_audit_and_sbom_require_the_complete_version_graph(self) -> None:
        tools = {"distributions": {"pyyaml": "6.0.3", "jsonschema": "4.26.0"}}
        audit = {"dependencies": [{"name": name, "version": version, "vulns": []}
                                  for name, version in tools["distributions"].items()]}
        sbom = {"bomFormat": "CycloneDX", "specVersion": "1.6",
                "components": [{"name": name, "version": version}
                               for name, version in tools["distributions"].items()]}
        verify_audit(tools, audit)
        verify_sbom(tools, sbom)
        for kind in ("missing", "version", "duplicate", "finding"):
            value = copy.deepcopy(audit)
            if kind == "missing":
                value["dependencies"].pop()
            elif kind == "version":
                value["dependencies"][0]["version"] = "6.0.2"
            elif kind == "duplicate":
                value["dependencies"].append(value["dependencies"][0])
            else:
                value["dependencies"][0]["vulns"] = [{"id": "synthetic-unaccepted"}]
            with self.subTest(contract="audit", kind=kind), self.assertRaises(ValueError):
                verify_audit(tools, value)
        for kind in ("missing", "version", "duplicate", "format"):
            value = copy.deepcopy(sbom)
            if kind == "missing":
                value["components"].pop()
            elif kind == "version":
                value["components"][0]["version"] = "6.0.2"
            elif kind == "duplicate":
                value["components"].append(value["components"][0])
            else:
                value["specVersion"] = "1.5"
            with self.subTest(contract="sbom", kind=kind), self.assertRaises(ValueError):
                verify_sbom(tools, value)


class ToolchainProcessOwnershipTest(unittest.TestCase):
    def test_completed_child_is_reaped(self) -> None:
        synchronize([sys.executable, "-B", "-c", "pass"], dict(os.environ), timeout=2)

    def _descendant_command(self, path: pathlib.Path, hold_parent: bool) -> list[str]:
        child = ("import os,signal,time,pathlib; signal.signal(signal.SIGTERM,signal.SIG_IGN); "
                 f"pathlib.Path({str(path)!r}).write_text(str(os.getpid())); time.sleep(30)")
        parent = ("import pathlib,subprocess,sys,time; "
                  f"subprocess.Popen([sys.executable,'-B','-c',{child!r}]); "
                  f"path=pathlib.Path({str(path)!r}); "
                  "deadline=time.monotonic()+2\n"
                  "while not path.exists():\n"
                  "    assert time.monotonic()<deadline\n"
                  "    time.sleep(.01)\n")
        if hold_parent:
            parent += "time.sleep(30)\n"
        return [sys.executable, "-B", "-c", parent]

    def _assert_descendant_not_live(self, path: pathlib.Path) -> None:
        self.assertTrue(path.is_file(), "fixture child never became ready")
        status = pathlib.Path("/proc") / path.read_text() / "stat"
        try:
            raw = status.read_text()
        except FileNotFoundError:
            return
        self.assertIn(raw[raw.rfind(")") + 2:].split()[0], {"Z", "X"})

    def test_timeout_drains_resistant_descendant(self) -> None:
        import subprocess

        with tempfile.TemporaryDirectory() as directory:
            path = pathlib.Path(directory) / "child.pid"
            started = time.monotonic()
            with self.assertRaises(subprocess.TimeoutExpired):
                synchronize(self._descendant_command(path, True), dict(os.environ), timeout=0.5)
            self.assertLess(time.monotonic() - started, 6)
            self._assert_descendant_not_live(path)

    def test_fast_parent_retains_group_until_descendant_drains(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            path = pathlib.Path(directory) / "child.pid"
            started = time.monotonic()
            synchronize(self._descendant_command(path, False), dict(os.environ), timeout=3)
            self.assertLess(time.monotonic() - started, 6)
            self._assert_descendant_not_live(path)

    def test_launch_boundary_interrupt_retains_owned_child_handle(self) -> None:
        import signal
        import subprocess
        from unittest.mock import patch

        from sync_tools import drain_owned_group

        actual_popen = subprocess.Popen
        created = []

        def launch_then_signal(*args, **kwargs):
            child = actual_popen(*args, **kwargs)
            created.append(child)
            # Arrives after creation, before Popen returns to the assignment.
            os.kill(os.getpid(), signal.SIGTERM)
            return child

        try:
            with patch("sync_tools.subprocess.Popen", side_effect=launch_then_signal):
                with self.assertRaises(InterruptedError):
                    synchronize([sys.executable, "-B", "-c", "import time; time.sleep(30)"],
                                dict(os.environ), timeout=2)
            self.assertEqual(len(created), 1)
            self.assertIsNotNone(created[0].returncode, "launch-boundary interrupt lost child ownership")
        finally:
            # A failed control must also join its actual child before leaving.
            for child in created:
                if child.returncode is None:
                    drain_owned_group(child, terminate=True)
